create or replace function private.user_can_access_cabinet(target_cabinet_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public, private
as $$
  select exists (
    select 1
    from public.cabinets c
    left join public.cabinet_memberships cm
      on cm.cabinet_id = c.id
     and cm.user_id = auth.uid()
     and cm.status = 'active'
    where c.id = target_cabinet_id
      and (
        c.owner_user_id = auth.uid()
        or cm.id is not null
      )
  );
$$;

create or replace function private.user_can_access_tracked_medicine(target_tracked_medicine_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public, private
as $$
  select exists (
    select 1
    from public.tracked_medicines tm
    where tm.id = target_tracked_medicine_id
      and (
        tm.owner_user_id = auth.uid()
        or (tm.cabinet_id is not null and private.user_can_access_cabinet(tm.cabinet_id))
      )
  );
$$;

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  given_name text;
  family_name text;
  full_name text;
begin
  given_name := nullif(new.raw_user_meta_data ->> 'given_name', '');
  family_name := nullif(new.raw_user_meta_data ->> 'family_name', '');
  full_name := nullif(new.raw_user_meta_data ->> 'full_name', '');

  insert into public.profiles (id, display_name)
  values (new.id, coalesce(full_name, new.email))
  on conflict (id) do nothing;

  insert into public.user_settings (user_id, catalog_country, business_country)
  values (new.id, 'it', 'it')
  on conflict (user_id) do nothing;

  insert into public.people (owner_user_id, name, surname, is_account)
  values (
    new.id,
    coalesce(given_name, split_part(coalesce(full_name, ''), ' ', 1)),
    coalesce(family_name, nullif(trim(substr(coalesce(full_name, ''), length(split_part(coalesce(full_name, ''), ' ', 1)) + 1)), '')),
    true
  )
  on conflict do nothing;

  return new;
end;
$$;

