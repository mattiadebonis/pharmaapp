create or replace view public.catalog_it_search_v1 as
select
  'it'::text as country,
  p.source,
  private.catalog_compose_key('it', p.source, 'product', p.source_product_id) as product_id,
  private.catalog_compose_key('it', p.source, 'package', pk.source_package_id) as package_id,
  private.catalog_family_key('it', p.source, p.family_id) as family_id,
  p.display_name,
  p.brand_name,
  p.generic_name,
  coalesce(
    nullif(p.generic_name, ''),
    nullif((
      select string_agg(ci.name, ', ' order by ci.sort_order, ci.id)
      from public.catalog_it_raw_ingredients ci
      where ci.source_product_id = p.source_product_id
    ), ''),
    p.display_name
  ) as principle,
  coalesce(pk.requires_prescription, p.requires_prescription, false) as requires_prescription,
  pk.display_name as package_label,
  coalesce(pk.unit_count, 1) as units,
  coalesce(nullif(pk.package_type, ''), pk.display_name, 'Package') as tipologia,
  coalesce(round(pk.strength_value)::integer, 0) as valore,
  coalesce(pk.strength_unit, '') as unita,
  case
    when pk.volume_value is null or pk.volume_unit is null or btrim(pk.volume_unit) = '' then ''
    else trim(to_char(pk.volume_value, 'FM999999990.########')) || ' ' || pk.volume_unit
  end as volume,
  coalesce(pk.availability, p.availability, 'unknown') as availability,
  pk.package_code as catalog_code,
  jsonb_build_object(
    'country', 'it',
    'source', p.source,
    'product_id', private.catalog_compose_key('it', p.source, 'product', p.source_product_id),
    'package_id', private.catalog_compose_key('it', p.source, 'package', pk.source_package_id),
    'family_id', private.catalog_family_key('it', p.source, p.family_id),
    'display_name', p.display_name,
    'generic_name', p.generic_name,
    'package_label', pk.display_name,
    'catalog_code', pk.package_code,
    'availability', coalesce(pk.availability, p.availability, 'unknown')
  ) as catalog_snapshot
from public.catalog_it_raw_products p
join public.catalog_it_raw_packages pk on pk.source_product_id = p.source_product_id;

