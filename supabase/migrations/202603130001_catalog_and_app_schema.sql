create or replace function public.fetch_catalog_product_v1(country text, product_id text)
returns jsonb
language plpgsql
security definer
set search_path = public, private
as $$
declare
  result jsonb;
begin
  if lower(country) not in ('it', 'us') then
    raise exception 'invalid catalog country'
      using errcode = '22023';
  end if;

  if lower(country) = 'it' then
    select to_jsonb(v) into result
    from public.catalog_it_product_detail_v1 v
    where v.id = product_id;
  else
    select to_jsonb(v) into result
    from public.catalog_us_product_detail_v1 v
    where v.id = product_id;
  end if;

  if result is null then
    raise exception 'catalog product not found'
      using errcode = 'P0002';
  end if;

  return result;
end;
$$;

