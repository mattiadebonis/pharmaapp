create or replace function private.touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = timezone('utc', now());
  return new;
end;
$$;

create or replace function private.catalog_compose_key(
  country_code text,
  source_name text,
  entity_kind text,
  source_identifier text
)
returns text
language sql
immutable
as $$
  select lower(country_code) || ':' || lower(source_name) || ':' || lower(entity_kind) || ':' || source_identifier;
$$;

create or replace function private.catalog_family_key(
  country_code text,
  source_name text,
  family_identifier text
)
returns text
language sql
immutable
as $$
  select case
    when family_identifier is null or btrim(family_identifier) = '' then null
    else lower(country_code) || ':' || lower(source_name) || ':family:' || family_identifier
  end;
$$;

